// KEYBOARD.DRV : the record of an installed language, or null.
inline const Layout *FindLayout(unsigned language)
{
    for (const auto &layout : Tables::Layouts)
        if (layout.language == (language & 65535)) return &layout;
    return nullptr;
}

// KEYBOARD.DRV keeps the pending dead key, the Alt sequence and its leading
// zero in its own data segment, which every process of the system shares.
// NEO98 keeps them the same way, for the whole runtime.
inline Pending &DriverState()
{
    static Pending pending;
    return pending;
}

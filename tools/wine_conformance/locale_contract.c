START_TEST(locale_contract)
{
    unsigned i,j,k;char value[256];
    for(i=0;i<sizeof(locales)/sizeof(locales[0]);++i){
        DWORD hash=2166136261u;unsigned count=0;
        for(j=0;j<sizeof(fields)/sizeof(fields[0]);++j){
            int n=GetLocaleInfoA(locales[i],fields[j]|LOCALE_NOUSEROVERRIDE,value,sizeof(value));
            ok(n>0,"locale %04lx field %04lx failed, error %lu\n",locales[i],fields[j],GetLastError());
            if(n>0){++count;for(k=0;k<(unsigned)n;++k)hash=(hash^(unsigned char)value[k])*16777619u;}
        }
        trace("LOCALE_DATA lcid=%04lx fields=%u hash=%08lx\n",locales[i],count,hash);
    }
    GetLocaleInfoA(0x40a,LOCALE_SDECIMAL|LOCALE_NOUSEROVERRIDE,value,sizeof value);
    ok(!strcmp(value,","),"Spanish decimal separator: %s\n",value);
}

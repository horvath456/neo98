"""Reconstruct the KERNEL32 NTSTATUS-to-Win32 tables behind K32_RtlNtStatusToDosError.

The original body walks a range table whose first row sits eight bytes before its loop start (:,
count, width) and indexes a table of 16-bit values. This script reads
both from the local DLL, writes src/win98_nt_status.h and offers the same
tables to the differential test. No original code bytes are copied.
"""
import hashlib
import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DLL = ROOT / 'build/programs/KERNEL32.DLL'
SHA256 = '9c8d574f84bfbbb6521dac54d0bfaf7a4c8fee07e468525cdb9da7db418e6c7e'
RANGES, RANGES_END, VALUES = 0xbff79ce0, 0xbff79fd0, 0xbff796c8


def tables():
    import pefile
    data = DLL.read_bytes()
    assert hashlib.sha256(data).hexdigest() == SHA256, 'unexpected KERNEL32.DLL'
    pe = pefile.PE(data=data)
    base = pe.OPTIONAL_HEADER.ImageBase
    rows = []
    for va in range(RANGES, RANGES_END, 8):
        rows.append(struct.unpack('<IHH', pe.get_data(va - base, 8)))
    assert rows[-1][0] == 0xffffffff and rows[-1][1:] == (1, 1), rows[-1]
    rows.pop()  # The terminator never matches a status below 0xffffffff.
    words = sum(count * width for _, count, width in rows)
    values = struct.unpack('<%dH' % words, pe.get_data(VALUES - base, words * 2))
    return rows, values


def header(rows, values):
    lines = ['// SPDX-License-Identifier: GPL-2.0-or-later',
             '// Generated by tools/kernel_misc_status_table.py from the local original',
             '// KERNEL32.DLL (SHA-256 %s).' % SHA256,
             '// Range table (the walk credits the row before its loop start) and',
             '// value table. Freestanding; no libc.',
             '#pragma once',
             'namespace Win98NtStatus',
             '{',
             'struct Range { unsigned base; unsigned short count, width; };',
             'static const Range Ranges[] = {']
    for base_, count, width in rows:
        lines.append('    {0x%08x, %d, %d},' % (base_, count, width))
    lines += ['};', 'static const unsigned short Values[] = {']
    for i in range(0, len(values), 12):
        lines.append('    ' + ', '.join('0x%04x' % v for v in values[i:i + 12]) + ',')
    lines += ['};',
              'constexpr unsigned RangeCount = sizeof Ranges / sizeof Ranges[0];',
              '// : the customer bit passes the status through, HRESULT-wrapped',
              '// Win32 codes unwrap, 0xD... facilities fold to 0xC..., then the range walk.',
              '// Misses map to 317 unless the facility is 0xC001 (network status codes).',
              'inline unsigned ToDosError(unsigned status)',
              '{',
              '    if (status & 0x20000000u) return status;',
              '    if ((status & 0xffff0000u) == 0x80070000u) return status & 0xffffu;',
              '    if ((status & 0xf0000000u) == 0xd0000000u) status &= 0xcfffffffu;',
              '    unsigned index = 0, position = 0;',
              '    while (index < RangeCount && Ranges[index].base <= status)',
              '    {',
              '        position += Ranges[index].count * Ranges[index].width;',
              '        ++index;',
              '    }',
              '    if (index)',
              '    {',
              '        const Range &row = Ranges[index - 1];',
              '        const unsigned offset = status - row.base;',
              '        if (row.count > offset)',
              '        {',
              '            position -= row.count * row.width;',
              '            position += row.width * offset;',
              '            if (row.width == 1) return Values[position];',
              '            return Values[position] | (unsigned)Values[position + 1] << 16;',
              '        }',
              '    }',
              '    if ((status & 0xffff0000u) == 0xc0010000u) return status & 0xffffu;',
              '    return 317;',
              '}',
              '} // namespace Win98NtStatus',
              '']
    return '\n'.join(lines)


def main():
    rows, values = tables()
    text = header(rows, values)
    target = ROOT / 'src/win98_nt_status.h'
    if len(sys.argv) > 1 and sys.argv[1] == '--check':
        assert target.read_text() == text, 'src/win98_nt_status.h differs from the original tables'
        print('win98_nt_status.h matches the original tables: %d ranges, %d values' % (len(rows), len(values)))
        return
    target.write_text(text)
    print('wrote', target, len(rows), 'ranges', len(values), 'values')


if __name__ == '__main__':
    main()

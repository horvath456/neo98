#!/usr/bin/env python3
"""Copy the system message table out of the local KERNEL32.DLL.

FormatMessage with FORMAT_MESSAGE_FROM_SYSTEM reads message 11 (RT_MESSAGETABLE)
of KERNEL32. This writes that resource unchanged into a generated header so the
implemented lookup runs against the original data. The decoding algorithm is
implemented separately in src/win98_format_message.h.

Reads the original file only and writes into the ignored build directory.
"""
from __future__ import annotations

import hashlib
import json
from pathlib import Path
import struct

import sys

sys.path.insert(0, str(Path(__file__).resolve().parent))
from provenance import stamp as stamp_provenance    # noqa: E402

import pefile

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'build/generated'
SOURCE = ROOT / 'build/programs/KERNEL32.DLL'
MESSAGE_TABLE = 11


def resource(path: Path):
    pe = pefile.PE(str(path))
    try:
        for entry in pe.DIRECTORY_ENTRY_RESOURCE.entries:
            if entry.id != MESSAGE_TABLE:
                continue
            for name in entry.directory.entries:
                for language in name.directory.entries:
                    data = pe.get_data(language.data.struct.OffsetToData, language.data.struct.Size)
                    return name.id, language.id, bytes(data)
    finally:
        pe.close()
    raise ValueError('The local KERNEL32.DLL has no message table resource')


def summary(data: bytes):
    """Count what the original table holds, as a check on the copy."""
    blocks = struct.unpack('<I', data[:4])[0]
    identifiers, unicode_entries = 0, 0
    for index in range(blocks):
        low, high, offset = struct.unpack('<III', data[4 + index * 12:16 + index * 12])
        identifiers += high - low + 1
        position = offset
        for _ in range(low, high + 1):
            length, flags = struct.unpack('<HH', data[position:position + 4])
            if not length:
                break
            unicode_entries += flags & 1
            position += length
    return {'blocks': blocks, 'identifiers': identifiers, 'unicode_entries': unicode_entries}


def generate():
    OUT.mkdir(parents=True, exist_ok=True)
    header = OUT / 'win98_message_table.h'
    provenance = OUT / 'message-table-provenance.json'
    name, language, data = resource(SOURCE)
    digest = hashlib.sha256(SOURCE.read_bytes()).hexdigest()
    counts = summary(data)
    lines = ['// SPDX-License-Identifier: LicenseRef-Microsoft',
             '// Generated by tools/message_table_assets.py. Original resource bytes of',
             f'// the local KERNEL32.DLL, SHA-256 {digest},',
             f'// resource type {MESSAGE_TABLE} name {name} language {language}.',
             f'// {counts["blocks"]} blocks, {counts["identifiers"]} identifiers, '
             f'{counts["unicode_entries"]} of them Unicode.',
             '#pragma once', '',
             'namespace Win98MessageTable', '{',
             f'constexpr unsigned Language = {language};',
             f'constexpr unsigned Bytes = {len(data)};',
             'inline const unsigned char Data[] = {']
    for start in range(0, len(data), 16):
        lines.append('    ' + ''.join('0x%02x,' % byte for byte in data[start:start + 16]))
    lines += ['};', '} // namespace Win98MessageTable', '']
    header.write_text('\n'.join(lines))
    record = {'source': str(SOURCE.relative_to(ROOT)), 'source_sha256': digest,
              'resource': {'type': MESSAGE_TABLE, 'name': name, 'language': language,
                           'bytes': len(data), 'sha256': hashlib.sha256(data).hexdigest()},
              **counts,
              'generated_sha256': {header.name: hashlib.sha256(header.read_bytes()).hexdigest()},
              'meaning': 'Original resource bytes only. The lookup algorithm is implemented in '
                         'src/win98_format_message.h.'}
    stamp_provenance(record, 'message-table-provenance.json')
    provenance.write_text(json.dumps(record, indent=2) + '\n')
    return record


if __name__ == '__main__':
    print(json.dumps(generate(), indent=2))

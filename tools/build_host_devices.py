def icon_art(path):
    """The 16x16 image of an.ico with the most colours, as 0xRRGGBB pixels
    top-down and the 1-bit AND mask that CreateIcon takes."""
    data = path.read_bytes()
    count = struct.unpack_from('<H', data, 4)[0]
    best = None
    for i in range(count):
        width, height, _, _, _, _, size, offset = struct.unpack_from('<BBBBHHII', data, 6 + i * 16)
        if (width, height) != (16, 16): continue
        bits = struct.unpack_from('<H', data, offset + 14)[0]
        if best is None or bits > best[0]: best = (bits, offset)
    if best is None: raise SystemExit(f'{path} has no 16x16 image')
    bits, offset = best
    header, used = struct.unpack_from('<I', data, offset)[0], struct.unpack_from('<I', data, offset + 32)[0]
    colours = (used or 1 << bits) if bits <= 8 else 0
    palette = offset + header
    pixels_at = palette + colours * 4
    stride = (16 * bits + 31) // 32 * 4
    mask_at = pixels_at + stride * 16
    pixels, mask = [], []
    for y in range(16):
        row = 15 - y
        line = pixels_at + row * stride
        mask += list(data[mask_at + row * 4:mask_at + row * 4 + 2])
        for x in range(16):
            if bits > 8:
                b, g, r = data[line + x * (bits // 8):line + x * (bits // 8) + 3]
            else:
                byte = data[line + x * bits // 8]
                index = byte if bits == 8 else (byte >> (0 if x & 1 else 4)) & 15 if bits == 4 else (byte >> (7 - x % 8)) & 1
                b, g, r = data[palette + index * 4:palette + index * 4 + 3]
            transparent = mask[-2 + x // 8] & (0x80 >> (x % 8))
            pixels.append(0 if transparent else r << 16 | g << 8 | b)
    return pixels, mask


def icon_header(out):
    """eject_icons.h: the icons in tools/host_devices/icons as ART values."""
    text = '/* Generated by tools/build_host_devices.py from tools/host_devices/icons. */\n'
    for name in ('eject-tray', 'eject-dialog'):
        pixels, mask = icon_art(ICONS / (name + '.ico'))
        text += 'static const ART %s_art={{%s},{%s}};\n' % (name.replace('-', '_'), ','.join('0x%06x' % p for p in pixels), ','.join(str(m) for m in mask))
    try:
        from generated_file import write_text
    except ImportError:
        from tools.generated_file import write_text
    write_text(out / 'eject_icons.h', text)


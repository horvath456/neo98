def capture_driver(out, env):
    """NEO98CAP.DRV: only the version resource that capGetDriverDescription
    reads. The driver itself is native (src/win16_capture.cpp); USER's
    OpenDriver recognises the name and never loads this file."""
    rc, res, drv = out/'neo98cap.rc', out/'neo98cap.res', out/'NEO98CAP.DRV'
    rc.write_text(CAPTURE_RC)
    # Relative names: llvm-rc takes an absolute macOS path (/absolute/path/...) for
    # one of its own /options and then finds no input file.
    subprocess.run(['llvm-rc', '/fo', res.name, rc.name], env=env, check=True, cwd=out)
    subprocess.run(['lld-link', '/dll', '/noentry', '/machine:x86', '/timestamp:0', '/out:'+str(drv), str(res)], env=env, check=True)
    return drv


def ff_driver(out, env):
    """NEO98FF.DLL, the DirectInput force feedback driver (tools/host_devices/ffdriver.c)."""
    obj, lib, dll = out/'ffdriver.obj', out/'ffdriver-KERNEL32.lib', out/'NEO98FF.DLL'
    (out/'ffdriver-KERNEL32.def').write_text('LIBRARY KERNEL32.DLL\nEXPORTS\nCreateFileA@28\nDeviceIoControl@32\nGetTickCount@0\nLocalAlloc@8\nLocalFree@4\n')
    subprocess.run(['llvm-dlltool','-m','i386','-k','-d',str(out/'ffdriver-KERNEL32.def'),'-l',str(lib)],env=env,check=True)
    subprocess.run(['clang','--target=i686-pc-windows-msvc','-O2','-ffreestanding','-fno-builtin','-fno-stack-protector','-Wall','-Wextra','-Wno-unused-parameter',
                    '-c',str(ROOT/'tools/host_devices/ffdriver.c'),'-o',str(obj)],env=env,check=True)
    subprocess.run(['lld-link','/dll','/entry:DllMain','/nodefaultlib','/machine:x86','/timestamp:0','/subsystem:windows,4.0',
                    '/export:DllGetClassObject=_DllGetClassObject@12','/export:DllCanUnloadNow=_DllCanUnloadNow@0',
                    '/out:'+str(dll),str(obj),str(lib)],env=env,check=True)
    return dll


# The 16 colours of the VGA palette Windows 98 icons use.
VGA = [(0, 0, 0), (128, 0, 0), (0, 128, 0), (128, 128, 0), (0, 0, 128), (128, 0, 128), (0, 128, 128), (192, 192, 192),
       (128, 128, 128), (255, 0, 0), (0, 255, 0), (255, 255, 0), (0, 0, 255), (255, 0, 255), (0, 255, 255), (255, 255, 255)]


def camera_picture(size):
    """The Camera icon, a camera ball on a stand: rows of VGA indices, None transparent."""
    s = size / 32
    cx, cy, body, lens = 15.5 * s, 13 * s, 11.5 * s, 6.5 * s
    rows = []
    for y in range(size):
        row = []
        for x in range(size):
            px, py = x + 0.5 - 0.5 * s + 0.5, y + 0.5 - 0.5 * s + 0.5
            dx, dy = px - (cx + 0.5), py - (cy + 0.5)
            d = (dx * dx + dy * dy) ** 0.5
            colour = None
            # The stand: a neck and a foot, drawn first so the ball covers them.
            if abs(px - (cx + 0.5)) <= 2.2 * s and cy + body - 2 * s <= py <= 28 * s:
                colour = 8 if px > cx + 0.5 else 7
            if 26.5 * s <= py <= 30.5 * s and abs(px - (cx + 0.5)) <= 9.5 * s:
                colour = 0 if py > 29.5 * s or abs(px - (cx + 0.5)) > 8.5 * s or py < 27.5 * s else (8 if px > cx + 3 * s else 7)
            if d <= body:
                # Light grey, white towards the top left, grey towards the bottom right.
                shade = (dx + dy) / body
                colour = 0 if d > body - max(1, s) else 15 if shade < -0.95 else 8 if shade > 0.75 else 7
                if d <= lens + 1.2 * s:
                    colour = 0
                if d <= lens:
                    colour = 8 if d > lens - max(1, s) else 4 if d > lens * 0.62 else 12 if d > lens * 0.3 else 0
                    hx, hy = dx + lens * 0.35, dy + lens * 0.35
                    if (hx * hx + hy * hy) ** 0.5 <= max(1.0, lens * 0.2):
                        colour = 15
                # The light of the camera, a green dot above the lens.
                if size >= 32 and abs(dx) <= 0.8 * s and -body + 2.2 * s <= dy <= -body + 3.6 * s:
                    colour = 10
            row.append(colour)
        rows.append(row)
    return rows


def write_icon(path, pictures):
    """An.ico of 4-bit images with their AND masks."""
    images = []
    for rows in pictures:
        size = len(rows)
        stride, mask_stride = (size * 4 + 31) // 32 * 4, (size + 31) // 32 * 4
        header = struct.pack('<IiiHHIIiiII', 40, size, size * 2, 1, 4, 0, (stride + mask_stride) * size, 0, 0, 16, 0)
        palette = b''.join(bytes((b, g, r, 0)) for r, g, b in VGA)
        pixels, mask = bytearray(), bytearray()
        for row in reversed(rows):
            line, bits = bytearray(stride), bytearray(mask_stride)
            for x, colour in enumerate(row):
                line[x // 2] |= (colour or 0) << (0 if x & 1 else 4)
                if colour is None:
                    bits[x // 8] |= 0x80 >> (x % 8)
            pixels += line
            mask += bits
        images.append((size, header + palette + pixels + mask))
    data = struct.pack('<HHH', 0, 1, len(images))
    offset = 6 + 16 * len(images)
    for size, image in images:
        data += struct.pack('<BBBBHHII', size, size, 16, 0, 1, 4, len(image), offset)
        offset += len(image)
    path.write_bytes(data + b''.join(image for _, image in images))


